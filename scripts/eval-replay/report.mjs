// metrics.md: the readable form of metrics.json (spec §11, §13). It shows numbers with their n and CI,
// and never a pass or a label: labels come only from evidence.json (EVID-1).
// Tiers from most to least capable (§5.2); any other tier name sorts after them.
const TIER_ORDER = ['full', 'basic', 'limited'];

const shown = (value, unit) =>
  value == null ? 'not measured' : `${value}${unit.startsWith('%') ? '' : ' '}${unit}`;
const interval = (ci95, unit) => (ci95 == null ? '' : ` (95% CI ${ci95[0]}–${ci95[1]} ${unit})`);
const rate = (part, whole) => (whole ? `${Math.round((1000 * part) / whole) / 10}%` : 'not measured');
const tierRank = (tier) => {
  const index = TIER_ORDER.indexOf(tier);
  return index === -1 ? TIER_ORDER.length : index;
};

// §5.4: if a higher tier does not show lower error, say so; the rating is then a feature gate only.
function tierComparison(rows) {
  const notLower = [];
  for (const [key, unit, name] of [
    ['hrMaeBpm', 'bpm', 'HR'],
    ['intervalMaeMs', 'ms', 'interval'],
  ]) {
    const measured = rows.filter((row) => row[key] != null);
    for (let i = 0; i + 1 < measured.length; i += 1) {
      const [higher, lower] = [measured[i], measured[i + 1]];
      if (higher[key] >= lower[key])
        notLower.push(
          `${higher.tier} does not show lower ${name} error than ${lower.tier} (${higher[key]} vs ${lower[key]} ${unit})`,
        );
    }
  }
  const comparable = ['hrMaeBpm', 'intervalMaeMs'].some(
    (key) => rows.filter((row) => row[key] != null).length >= 2,
  );
  if (!comparable) return 'Fewer than two tiers have measured error, so tiers cannot be compared yet.';
  if (notLower.length === 0) return 'Each higher tier shows lower error than the tier below it in this data.';
  return `${notLower.map((line) => `${line[0].toUpperCase()}${line.slice(1)}.`).join(' ')} The rating is a feature gate only; it does not predict accuracy.`;
}

export function renderReport(metrics) {
  const tiers = [...metrics.perTier].sort(
    (a, b) => tierRank(a.tier) - tierRank(b.tier) || a.tier.localeCompare(b.tier),
  );
  const recompute =
    metrics.recompute?.matches == null
      ? 'not run yet'
      : `${metrics.recompute.matches ? 'matches' : 'does not match'} (${metrics.recompute.agent})`;
  return [
    '# Lumen validation metrics',
    '',
    `Commit ${metrics.commit ?? 'unknown'}, ${metrics.date ?? 'undated'}. Generated by \`npm run eval:replay\` from`,
    '`metrics.json`; do not edit by hand. Evidence labels are in `evidence.json`.',
    '',
    '| Measure | Value | n |',
    '|---|---|---|',
    `| HR error vs Polar H10, at rest (DSP-A) | ${shown(metrics.hr.maeBpm, 'bpm')}${interval(metrics.hr.ci95, 'bpm')} | ${metrics.hr.people} people, ${metrics.hr.readings} readings, ${metrics.hr.phones} phones |`,
    `| Interval error vs Polar H10 (DSP-B) | ${shown(metrics.intervals.maeMs, 'ms')}${interval(metrics.intervals.ci95, 'ms')} | |`,
    `| RMSSD within 10% of Polar, ≥ 60 fps (DSP-B) | ${shown(metrics.rmssd.withinPct, '% of readings')}; median error ${shown(metrics.rmssd.medianErrorPct, '%')} | ${metrics.rmssd.people} people |`,
    `| Breathing-rate error, paced (RESP-1) | ${shown(metrics.resp.maeBrpm, 'breaths/min')} | ${metrics.resp.people} people |`,
    `| False "irregular" on Polar-confirmed sinus (ML-5) | ${rate(metrics.ml5.falseIrregular, metrics.ml5.sinusReadings)} | ${metrics.ml5.falseIrregular} of ${metrics.ml5.sinusReadings} readings |`,
    `| Deliberate artifacts rejected or Inconclusive | ${rate(metrics.artifactCaptures.rejectedOrInconclusive, metrics.artifactCaptures.total)} | ${metrics.artifactCaptures.rejectedOrInconclusive} of ${metrics.artifactCaptures.total} captures |`,
    `| First readings that were conclusive (UX-1) | ${rate(metrics.ux1.conclusive, metrics.ux1.firstReadings)} | ${metrics.ux1.conclusive} of ${metrics.ux1.firstReadings} |`,
    '',
    `Polar-paired captures: ${metrics.polarPairedCaptures}. Independent recompute (VER-1): ${recompute}.`,
    '',
    '## Error by phone tier (COMP-2)',
    '',
    '| Tier | Phones | HR error | Interval error |',
    '|---|---|---|---|',
    ...tiers.map(
      (row) =>
        `| ${row.tier} | ${row.phones} | ${shown(row.hrMaeBpm, 'bpm')} | ${shown(row.intervalMaeMs, 'ms')} |`,
    ),
    '',
    tierComparison(tiers),
    '',
  ].join('\n');
}
